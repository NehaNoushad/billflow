import Link from "next/link";
import { methodLabel } from "@/components/billing/labels";
import { notFound } from "next/navigation";
import { CheckCircle2, Download, FileDown, Pencil, XCircle } from "lucide-react";
import { Button } from "@/components/ui/button";
import { connectDB } from "@/lib/db";
import { ActivityLog, Invoice, InvoiceLine, Payment } from "@/models";
import { canAccessCustomer, requirePage } from "@/lib/auth/guard";
import { getSettings, isObjectId } from "@/lib/utils-server";
import { businessToday, formatDate, formatDateTime, toDateInput } from "@/lib/dates";
import { formatBps, formatMoney } from "@/lib/money";
import { emailConfigured } from "@/lib/email";
import { isOverdue } from "@/services/invoices";
import { DetailList, EmptyState, PageHeader, Panel, StatusBadge } from "@/components/app/ui-bits";
import { ActionButton } from "@/components/app/action-button";
import { RecordPaymentDialog } from "@/components/billing/record-payment-dialog";
import { EmailInvoiceButton, PrintButton } from "@/components/billing/misc";
import { cancelInvoiceAction, confirmInvoiceAction } from "@/actions/invoices";

export default async function InvoiceDetailPage({ params }: { params: Promise<{ id: string }> }) {
  const user = await requirePage("invoices.manage");
  const { id } = await params;
  if (!isObjectId(id)) notFound();
  await connectDB();
  const invoice = await Invoice.findById(id).lean();
  if (!invoice || !(await canAccessCustomer(user, invoice.customer))) notFound();
  const [lines, payments, settings] = await Promise.all([
    InvoiceLine.find({ invoice: invoice._id }).sort({ position: 1 }).lean(),
    Payment.find({ invoice: invoice._id }).sort({ paymentDate: 1, createdAt: 1 }).lean(),
    getSettings(),
  ]);
  const activity = await ActivityLog.find({ entityId: { $in: [invoice._id, ...payments.map((p) => p._id)] } }).sort({ createdAt: -1 }).limit(20).lean();
  const today = businessToday();
  const overdue = isOverdue(invoice, today);
  const hasPayments = payments.some((p) => p.status === "COMPLETED");
  const payable = invoice.status === "CONFIRMED" && invoice.amountDue > 0;
  const c = invoice.customerSnapshot;

  return (
    <>
      <PageHeader
        title={invoice.number}
        description={`${invoice.source === "BILLING_ENGINE" ? "Generated by the billing engine" : "Manual invoice"} · issued ${formatDate(invoice.invoiceDate)}`}
        back={{ href: "/invoices", label: "Invoices" }}
        actions={
          <>
            {invoice.status === "DRAFT" && (
              <>
                <Button variant="outline" size="sm" nativeButton={false} render={<Link href={`/invoices/${id}/edit`} />}>
                  <Pencil className="size-4" /> Edit
                </Button>
                <ActionButton action={confirmInvoiceAction.bind(null, id)} variant="default" confirm={{ title: "Confirm this invoice?", description: "Confirmed invoices are locked: lines and amounts can no longer be edited, and the customer can see and pay it.", confirmLabel: "Confirm invoice" }}>
                  <CheckCircle2 className="size-4" /> Confirm
                </ActionButton>
              </>
            )}
            {payable && <RecordPaymentDialog invoiceId={id} invoiceNumber={invoice.number} outstanding={invoice.amountDue} allowPartial={settings.allowPartialPayments ?? true} today={toDateInput(today)} />}
            {invoice.status !== "DRAFT" && invoice.status !== "CANCELLED" && <EmailInvoiceButton invoiceId={id} enabled={emailConfigured()} emailedAt={invoice.emailedAt ? String(invoice.emailedAt) : null} />}
            <Button variant="outline" size="sm" nativeButton={false} render={<a href={`/api/invoices/${id}/pdf`} />}>
              <Download className="size-4" /> PDF
            </Button>
            <PrintButton />
            {(invoice.status === "DRAFT" || invoice.status === "CONFIRMED") && (
              <ActionButton
                action={cancelInvoiceAction.bind(null, id)}
                variant="destructive"
                disabled={hasPayments}
                title={hasPayments ? "Invoices with recorded payments cannot be cancelled" : undefined}
                confirm={{ title: `Cancel ${invoice.number}?`, description: "The invoice will be kept for audit purposes but no longer counts as owed. This cannot be undone.", confirmLabel: "Cancel invoice", destructive: true, reasonLabel: "Reason for cancellation", reasonRequired: true }}
              >
                <XCircle className="size-4" /> Cancel
              </ActionButton>
            )}
          </>
        }
      />

      <div className="grid gap-6 lg:grid-cols-3">
        <div className="space-y-6 lg:col-span-2">
          <section className="print-area rounded-xl border bg-card p-6 shadow-xs">
            <div className="flex flex-col justify-between gap-4 border-b pb-5 sm:flex-row">
              <div>
                <p className="text-xs font-medium tracking-wide text-muted-foreground uppercase">From</p>
                <p className="mt-1 font-semibold">{settings.companyName}</p>
                <p className="text-sm text-muted-foreground">{settings.companyAddress}</p>
                {settings.companyTaxId && <p className="text-sm text-muted-foreground">GSTIN: {settings.companyTaxId}</p>}
              </div>
              <div className="sm:text-right">
                <p className="text-xs font-medium tracking-wide text-muted-foreground uppercase">Tax invoice</p>
                <p className="mt-1 text-lg font-semibold">{invoice.number}</p>
                <div className="mt-1">
                  <StatusBadge status={overdue ? "OVERDUE" : invoice.status} />
                </div>
              </div>
            </div>
            <div className="grid gap-6 border-b py-5 sm:grid-cols-2">
              <div>
                <p className="text-xs font-medium tracking-wide text-muted-foreground uppercase">Bill to</p>
                <Link href={`/customers/${invoice.customer}`} className="mt-1 block font-semibold hover:underline">
                  {c?.companyName || c?.name}
                </Link>
                {c?.companyName && <p className="text-sm">{c?.name}</p>}
                <p className="text-sm text-muted-foreground">{c?.email}</p>
                {c?.address && <p className="text-sm text-muted-foreground">{c.address}</p>}
                {c?.taxId && <p className="text-sm text-muted-foreground">GSTIN: {c.taxId}</p>}
              </div>
              <DetailList
                items={[
                  { label: "Invoice date", value: formatDate(invoice.invoiceDate) },
                  { label: "Due date", value: <span className={overdue ? "text-red-600" : ""}>{formatDate(invoice.dueDate)}</span> },
                  { label: "Payment terms", value: `${invoice.paymentTermsDays ?? 0} days` },
                  { label: "Billing period", value: invoice.periodStart ? `${formatDate(invoice.periodStart)} – ${formatDate(invoice.periodEnd)}` : "—" },
                  {
                    label: "Subscription",
                    value: invoice.subscription ? (
                      <Link href={`/subscriptions/${invoice.subscription}`} className="text-primary hover:underline">
                        {invoice.subscriptionNumber}
                      </Link>
                    ) : (
                      "—"
                    ),
                  },
                  { label: "Source", value: invoice.source === "BILLING_ENGINE" ? "Billing engine" : "Manual" },
                ]}
              />
            </div>
            <div className="overflow-x-auto py-5">
              <table className="w-full min-w-[560px] text-sm">
                <thead className="border-b text-left text-xs text-muted-foreground">
                  <tr>
                    <th className="py-2 font-medium">Item</th>
                    <th className="py-2 text-right font-medium">Qty</th>
                    <th className="py-2 text-right font-medium">Unit price</th>
                    <th className="py-2 text-right font-medium">Discount</th>
                    <th className="py-2 text-right font-medium">Tax</th>
                    <th className="py-2 text-right font-medium">Amount</th>
                  </tr>
                </thead>
                <tbody>
                  {lines.map((l) => (
                    <tr key={String(l._id)} className="border-b last:border-0">
                      <td className="py-2.5">
                        <div className="font-medium">{l.productName}</div>
                        <div className="text-xs text-muted-foreground">
                          {[l.variantName, (l.taxes ?? []).map((t: { name?: string | null }) => `${t.name}`).join(" + ")].filter(Boolean).join(" · ")}
                        </div>
                      </td>
                      <td className="py-2.5 text-right tabular-nums">{l.quantity}</td>
                      <td className="py-2.5 text-right tabular-nums">{formatMoney(l.unitPrice)}</td>
                      <td className="py-2.5 text-right text-emerald-700 tabular-nums">{l.discountAmount ? `−${formatMoney(l.discountAmount)}` : "—"}</td>
                      <td className="py-2.5 text-right tabular-nums">{formatMoney(l.taxAmount)}</td>
                      <td className="py-2.5 text-right font-medium tabular-nums">{formatMoney(l.total)}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
            <div className="flex flex-col gap-4 sm:flex-row sm:justify-between">
              <div className="max-w-sm text-sm text-muted-foreground">{invoice.notes && <p className="whitespace-pre-line">{invoice.notes}</p>}</div>
              <dl className="w-full space-y-1.5 text-sm sm:w-72">
                <Row label="Subtotal" value={formatMoney(invoice.subtotal)} />
                {(invoice.discounts as { name: string; type: string; value: number; amount: number }[] | undefined)?.map((d, i) => (
                  <Row key={i} label={`${d.name}${d.type === "PERCENTAGE" ? ` (${formatBps(d.value)})` : ""}`} value={`−${formatMoney(d.amount)}`} className="text-emerald-700" />
                ))}
                {(invoice.taxBreakdown as { name?: string | null; amount?: number | null }[] | undefined)?.map((t, i) => (
                  <Row key={i} label={t.name ?? "Tax"} value={formatMoney(t.amount ?? 0)} />
                ))}
                <Row label="Total" value={formatMoney(invoice.total)} strong />
                <Row label="Amount paid" value={formatMoney(invoice.amountPaid)} className="text-emerald-700" />
                <Row label="Balance due" value={formatMoney(invoice.status === "CANCELLED" ? 0 : invoice.amountDue)} strong className={overdue ? "text-red-600" : ""} />
              </dl>
            </div>
            {invoice.status === "CANCELLED" && (
              <p className="mt-4 rounded-lg bg-red-50 px-3 py-2 text-sm text-red-700">
                Cancelled {formatDateTime(invoice.cancelledAt)}
                {invoice.cancelReason ? ` — ${invoice.cancelReason}` : ""}
              </p>
            )}
          </section>
        </div>

        <div className="no-print space-y-6">
          <Panel title="Payments" description="Recorded payments — no live gateway is charged." bodyClassName="p-0">
            {payments.length === 0 ? (
              <EmptyState title="No payments yet" description={payable ? "Record a payment when the customer pays." : undefined} />
            ) : (
              <ul className="divide-y">
                {payments.map((p) => (
                  <li key={String(p._id)} className="flex items-center justify-between gap-3 px-5 py-3 text-sm">
                    <div>
                      <div className="font-medium">
                        {formatMoney(p.amount)} <span className="font-normal text-muted-foreground">via {methodLabel(p.method)}</span>
                      </div>
                      <div className="text-xs text-muted-foreground">
                        {p.number} · {formatDate(p.paymentDate)}
                        {p.transactionRef ? ` · ${p.transactionRef}` : ""}
                        {p.simulated ? " · simulated" : ""}
                      </div>
                    </div>
                    <div className="flex items-center gap-2">
                      {p.status !== "COMPLETED" && <StatusBadge status={p.status} />}
                      <a href={`/api/payments/${p._id}/receipt`} className="text-muted-foreground hover:text-foreground" title="Download receipt">
                        <FileDown className="size-4" />
                      </a>
                    </div>
                  </li>
                ))}
              </ul>
            )}
          </Panel>
          <Panel title="Activity" bodyClassName="p-0">
            {activity.length === 0 ? (
              <p className="px-5 py-4 text-sm text-muted-foreground">No activity recorded.</p>
            ) : (
              <ul className="divide-y">
                {activity.map((a) => (
                  <li key={String(a._id)} className="px-5 py-3 text-sm">
                    <p>{a.message}</p>
                    <p className="text-xs text-muted-foreground">
                      {a.actorName} · {formatDateTime(a.createdAt)}
                    </p>
                  </li>
                ))}
              </ul>
            )}
          </Panel>
        </div>
      </div>
    </>
  );
}

function Row({ label, value, strong, className }: { label: string; value: string; strong?: boolean; className?: string }) {
  return (
    <div className={`flex justify-between ${strong ? "border-t pt-2 text-base font-semibold" : ""} ${className ?? ""}`}>
      <dt className={strong ? "" : "text-muted-foreground"}>{label}</dt>
      <dd className="tabular-nums">{value}</dd>
    </div>
  );
}
